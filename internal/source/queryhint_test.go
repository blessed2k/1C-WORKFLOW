package source

import (
	"strings"
	"testing"
)

// TestQueryErrorHint runs the rules over messages shaped like the ones 1C sent
// back in the journals (the wording and the <<?>> marker are kept, the object
// names are made up). want is a fragment the hint must contain; "" means no hint.
func TestQueryErrorHint(t *testing.T) {
	cases := []struct {
		name    string
		message string
		text    string
		want    string
	}{
		{
			name:    "keyword as table alias",
			message: "Ошибка выполнения запроса: {(1, 60)}: Ожидается имя\nВЫБРАТЬ В.Имя, В.Версия ИЗ РегистрСведений.Версии КАК <<?>>В ГДЕ В.Имя = &Имя",
			text:    "ВЫБРАТЬ В.Имя, В.Версия ИЗ РегистрСведений.Версии КАК В ГДЕ В.Имя = &Имя",
			want:    "«В» это ключевое слово",
		},
		{
			name:    "keyword as column alias",
			message: "Ошибка выполнения запроса: {(1, 70)}: Ожидается имя\nМАКСИМУМ(Д.Дата) КАК <<?>>По,",
			text:    "ВЫБРАТЬ МИНИМУМ(Д.Дата) КАК С, МАКСИМУМ(Д.Дата) КАК По ИЗ Документ.Счет КАК Д",
			want:    "«По» это ключевое слово",
		},
		{
			name:    "keyword alias found in the text when the marker is missing",
			message: "Ошибка выполнения запроса: Ожидается имя",
			text:    "ВЫБРАТЬ ИСТИНА КАК Есть ИЗ Справочник.Товары КАК Т",
			want:    "«Есть» это ключевое слово",
		},
		{
			name:    "ordinary aliases are not keywords",
			message: "Ошибка выполнения запроса: {(1, 9)}: Ожидается имя\nВЫБРАТЬ <<?>>",
			text:    "ВЫБРАТЬ Т.Ссылка КАК Ссылка, Т.Дата КАК Дата, Т.Значение КАК Значение ИЗ Справочник.Товары КАК Т",
			want:    "",
		},
		{
			name:    "keyword inside a string literal is not an alias",
			message: "Ошибка выполнения запроса: {(1, 9)}: Синтаксическая ошибка",
			text:    `ВЫБРАТЬ "поле КАК В" КАК Текст`,
			want:    "",
		},
		{
			name:    "union after order by",
			message: "Ошибка выполнения запроса: {(16, 1)}: Синтаксическая ошибка \"ОБЪЕДИНИТЬ\"\n<<?>>ОБЪЕДИНИТЬ ВСЕ",
			text:    "ВЫБРАТЬ 1 КАК Н ИЗ Справочник.Товары КАК Т УПОРЯДОЧИТЬ ПО Н\nОБЪЕДИНИТЬ ВСЕ\nВЫБРАТЬ 2 ИЗ Справочник.Товары КАК Т",
			want:    "УПОРЯДОЧИТЬ ПО ставится один раз",
		},
		{
			name:    "order by in an earlier batch statement is fine",
			message: "Ошибка выполнения запроса: {(3, 1)}: Синтаксическая ошибка",
			text:    "ВЫБРАТЬ 1 КАК Н УПОРЯДОЧИТЬ ПО Н;\nВЫБРАТЬ 2 ОБЪЕДИНИТЬ ВСЕ ВЫБРАТЬ 3",
			want:    "",
		},
		{
			name:    "order by in a subquery does not count",
			message: "Ошибка выполнения запроса: Синтаксическая ошибка",
			text:    "ВЫБРАТЬ * ИЗ (ВЫБРАТЬ ПЕРВЫЕ 1 Т.Ссылка КАК С ИЗ Справочник.Товары КАК Т УПОРЯДОЧИТЬ ПО Т.Код) КАК В1 ОБЪЕДИНИТЬ ВЫБРАТЬ 1",
			want:    "",
		},
		{
			name:    "maximum over a presentation",
			message: "Ошибка выполнения запроса: {(1, 106)}: Неверные параметры \"МАКСИМУМ\"\nВЫБРАТЬ П.Наименование, МАКСИМУМ(<<?>>ПРЕДСТАВЛЕНИЕ(Р.Роль)) КАК ПримерРоли",
			text:    "ВЫБРАТЬ П.Наименование, МАКСИМУМ(ПРЕДСТАВЛЕНИЕ(Р.Роль)) КАК ПримерРоли ИЗ Справочник.Профили КАК П",
			want:    "МАКСИМУМ и МИНИМУМ не принимают ПРЕДСТАВЛЕНИЕ()",
		},
		{
			name:    "presentation in order by",
			message: "Ошибка выполнения запроса: {(1, 18)}: Операция не разрешена в предложении \"УПОРЯДОЧИТЬ\"\nВЫБРАТЬ ПЕРВЫЕ 3 <<?>>ПРЕДСТАВЛЕНИЕ(О.Ссылка) КАК Организация",
			text:    "ВЫБРАТЬ ПЕРВЫЕ 3 ПРЕДСТАВЛЕНИЕ(О.Ссылка) КАК Организация ИЗ Справочник.Организации КАК О УПОРЯДОЧИТЬ ПО Организация",
			want:    "В УПОРЯДОЧИТЬ ПО нельзя ПРЕДСТАВЛЕНИЕ()",
		},
		{
			name:    "presentation compared to a string",
			message: "Ошибка выполнения запроса: {(9, 38)}: Неверные параметры в операции сравнения. Нельзя сравнивать поля неограниченной длины и поля несовместимых типов.\nИ ПРЕДСТАВЛЕНИЕ(Вер.Автор) <<?>>= \"Иванов\"",
			text:    "ВЫБРАТЬ Вер.Объект ИЗ РегистрСведений.Версии КАК Вер ГДЕ ИСТИНА И ПРЕДСТАВЛЕНИЕ(Вер.Автор) = \"Иванов\"",
			want:    "ПРЕДСТАВЛЕНИЕ() даёт строку неограниченной длины",
		},
		{
			name:    "presentation in like",
			message: "Ошибка выполнения запроса: {(11, 3)}: Неверные параметры \"ПОДОБНО\"\n(<<?>>ПРЕДСТАВЛЕНИЕ(О.Субконто2) ПОДОБНО \"%поставщик%\"",
			text:    "ВЫБРАТЬ 1",
			want:    "ПРЕДСТАВЛЕНИЕ() даёт строку неограниченной длины",
		},
		{
			name:    "unlimited comment compared",
			message: "Ошибка выполнения запроса: {(18, 19)}: Неверные параметры в операции сравнения. Нельзя сравнивать поля неограниченной длины и поля несовместимых типов.\nГДЕ Ш.Комментарий <<?>><> \"Перенесён\"",
			text:    "ВЫБРАТЬ 1 ИЗ Справочник.Шаблоны КАК Ш ГДЕ Ш.Комментарий <> \"Перенесён\"",
			want:    "ВЫРАЗИТЬ(Поле КАК СТРОКА(200))",
		},
		{
			name:    "unlimited string concatenated",
			message: "Ошибка выполнения запроса: {(5, 79)}: Неверные параметры \"+\"\nВЫРАЗИТЬ(К.НаименованиеПолное + \" | \" + <<?>>К.Комментарий КАК СТРОКА(500))",
			text:    "ВЫБРАТЬ 1",
			want:    "ВЫРАЗИТЬ(Поле КАК СТРОКА(200))",
		},
		{
			name:    "missing predefined value",
			message: "Ошибка выполнения запроса: {(1, 153)}: Неверные параметры \"Перечисление.ВидыОпераций.Зарплата\"\nГДЕ Д.ВидОперации В (ЗНАЧЕНИЕ(<<?>>Перечисление.ВидыОпераций.Зарплата))",
			text:    "ВЫБРАТЬ 1",
			want:    "get_predefined",
		},
		{
			name:    "field not found",
			message: "Ошибка выполнения запроса: {(1, 77)}: Поле не найдено \"Т.Цена\"\nВЫБРАТЬ <<?>>Т.Цена",
			text:    "ВЫБРАТЬ Т.Цена ИЗ Справочник.Товары КАК Т",
			want:    "get_object_structure",
		},
		{
			name:    "table not found",
			message: "Ошибка выполнения запроса: {(1, 15)}: Таблица не найдена \"Справочник.Товар\"",
			text:    "ВЫБРАТЬ 1 ИЗ Справочник.Товар КАК Т",
			want:    "object_exists",
		},
		{
			name:    "ambiguous field",
			message: "Ошибка выполнения запроса: {(48, 4)}: Неоднозначное поле \"Ссылка\"",
			text:    "ВЫБРАТЬ Ссылка ИЗ Справочник.Товары КАК Т ЛЕВОЕ СОЕДИНЕНИЕ Справочник.Цены КАК Ц ПО ИСТИНА",
			want:    "псевдонимом таблицы",
		},
		{
			name:    "field outside the group",
			message: "Ошибка выполнения запроса: {(1, 9)}: Поле не входит в группу \"Т.Код\"",
			text:    "ВЫБРАТЬ Т.Код, КОЛИЧЕСТВО(*) ИЗ Справочник.Товары КАК Т СГРУППИРОВАТЬ ПО Т.Наименование",
			want:    "СГРУППИРОВАТЬ ПО",
		},
		{
			name:    "unknown failure gets no hint",
			message: "Ошибка выполнения запроса: {(1, 1)}: Не задано значение параметра \"Дата\"",
			text:    "ВЫБРАТЬ 1 ГДЕ &Дата > ДАТАВРЕМЯ(2026, 1, 1)",
			want:    "",
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := QueryErrorHint(c.message, c.text)
			if c.want == "" {
				if got != "" {
					t.Fatalf("no hint expected, got %q", got)
				}
				return
			}
			if !strings.Contains(got, c.want) {
				t.Fatalf("hint %q does not contain %q", got, c.want)
			}
		})
	}
}
