// Package resolve превращает сырые ссылки парсера (internal/parse/bsl,
// internal/parse/meta, internal/parse/query) в разрешённые связи по
// семантике 1С (архитектура §19.1): квалифицированные вызовы, менеджерные
// вызовы, глобальные общие модули, platform builtins, экспортность,
// контексты клиент/сервер — с resolved/ambiguous/unresolved/dynamic и
// confidence.
//
// Пакет — чистая логика поверх фактов, переданных в памяти (Env). Он не
// открывает БД и не пишет SQL: это дело internal/store, вызывающего функции
// этого пакета внутри своей write-транзакции (пайплайн internal/index). Тесты гоняются на
// фикстурах, а не через реальный store.
//
// Одно исключение по импортам: objectedges.go (атрибуция код-фактов, веха В1)
// берёт из internal/store типы строк входа (store.RegisterAccessRow) и
// константы видов рёбер (store.EdgeWritesRegister и родня). Это словарь
// схемы, а не доступ к БД: SQL и драйвер остаются только в internal/store
// (RuleSQLOnlyInStore), а сама атрибуция по-прежнему ничего не открывает и
// не пишет — рёбра и бейджи она возвращает значениями. Границу этого
// исключения держит не комментарий, а гард: правило resolve-store-surface в
// internal/arch разрешает ровно перечисленную поверхность и красит любое
// другое обращение к store.
