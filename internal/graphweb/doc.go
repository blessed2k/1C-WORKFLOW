// Package graphweb — HTTP-транспорт объектного графа (веха В1, тикет 09,
// spec.md §6): маршруты раздела 8.1, сериализация конверта app.Response[T],
// выбор проекта, когда открыто несколько --project, и жизненный цикл HTTP-
// сервера. Вся бизнес-логика графа — в internal/app.ObjectGraphService
// (тикет 08, уже сдан); этот пакет только маршрутизирует и сериализует.
//
// # Несколько проектов и переоткрытие эпохи
//
// internal/app.Projects кэширует открытый *store.Store НАВСЕГДА при первом
// Active() (internal/app/projects.go: карта p.opened никогда не очищается,
// кроме явного Close). Значит «store переоткрывается при расхождении
// указателя эпохи» (spec §6, критерий R20.1/§44: «следующий запрос отвечает
// из новой эпохи без перезапуска») можно реализовать только ПЕРЕСОЗДАВ
// app.Projects целиком — более лёгкого «обновить» пути ни internal/app, ни
// internal/store не выставляют, а оба пакета вне зоны этого тикета (закрыты
// тасками 08 и 01/03 соответственно, менять их нельзя).
//
// Поэтому ProjectHandle.Open — не однократная инициализация, а фабрика:
// Handler зовёт её НА КАЖДЫЙ HTTP-запрос, получая свежий app.Projects (а
// значит и свежий store.Open — тот сам вычитывает текущий указатель эпохи
// при открытии, ADR-023) и закрывает его сразу после того, как ответ
// сериализован. Ответ всегда целиком из одной эпохи (одна read-транзакция
// внутри ObjectGraphService), потому что store.Open этого запроса открывает
// эпоху ровно один раз и больше её не переоткрывает.
//
// Упрощение, названо явно: это переоткрытие НА КАЖДЫЙ запрос, не только при
// доказанном расхождении — более лёгкой проверки «эпоха ещё та же» без
// полного store.Open в этом пакете нет (store.Status тоже читает поле уже
// открытого экземпляра, а не диск). Для localhost-инструмента с редкими
// кликами это не бюджетная проблема; если станет — обновление лежит уровнем
// ниже, в internal/store (дешёвый экспортированный «прочитать текущий номер
// эпохи без полного Open»), не здесь.
//
// Открытия одного проекта идут по одному (Handler.locks): параллельные
// store.Open одного индекса ловили SQLITE_BUSY на соединении писателя.
