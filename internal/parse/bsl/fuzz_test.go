package bsl

import "testing"

// FuzzParse проверяет два свойства, обязательных по критериям приёмки таска
// (R93i): Parse не паникует ни на каком входе, и любой выданный span лежит
// в границах входа — тот же контракт §18.3, что checkSpans проверяет на
// корпусе, здесь проверяется на случайных мутациях затравок.
//
// Затравки — синтетические фрагменты, покрывающие пункты чеклиста §12
// (директивы, препроцессор, Асинх, английский синтаксис, экранированные
// кавычки, многострочный литерал, сломанный метод, ложные вызовы в строках
// и комментариях, BOM, мусор), и один реальный фрагмент — то же поле
// «Обработчик.Процедура», что закреплено в helpers_test.go как регрессия
// с реальной выгрузки (ADR-3, п. 4.3).
func FuzzParse(f *testing.F) {
	seeds := []string{
		// Синтетические, по чеклисту §12.
		"Процедура А() Экспорт\nКонецПроцедуры",
		"Функция Ф(Знач П = \"а\"\"б\", Т = -1) Экспорт\nВозврат П;\nКонецФункции",
		"&НаКлиентеНаСервереБезКонтекста\nАсинх Процедура П()\nКонецПроцедуры",
		"#Область О\n#Если Сервер Тогда\n#КонецЕсли\n#КонецОбласти",
		"Т = \"ВЫБРАТЬ\n|\tА КАК Б\";\n// ЛожныйВызов()\n",
		"&AtClient\nAsync Function LoadAsync(Val Source = Undefined) Export\n\tReturn Source;\nEndFunction",
		"\xef\xbb\xbfПроцедура А() Экспорт\nКонецПроцедуры",
		"Процедура (((,,,=== Экспорт",
		"'20240101'",
		"Новый Тип(\"Строка\")",
		"Процедура БезЗакрытия()\n\tА = 1;\n",
		"",
		// Аннотации расширения с аргументом и без: битый аргумент не должен
		// ни ронять разбор, ни съедать имя метода.
		"&Вместо(\"ОбработкаПроведения\")\nПроцедура РасшБ_ОбработкаПроведения()\nКонецПроцедуры",
		"&НаСервере\n&После(\"ПриЗаписи\")\nПроцедура Р_ПриЗаписи()\nКонецПроцедуры",
		"&Вместо()\nПроцедура Р()\nКонецПроцедуры",
		"&Вместо(\nПроцедура Р()\nКонецПроцедуры",
		"&Вместо(123)\nПроцедура Р()\nКонецПроцедуры",
		"&Вместо(\"ОбработкаПроведения\")",
		// Реальный фрагмент выгрузки (helpers_test.go): ключевое слово после
		// точки — имя свойства, не начало объявления метода.
		"Процедура ПриДобавленииОбработчиковОбновления(Обработчики) Экспорт\n" +
			"\tОбработчик = Обработчики.Добавить();\n" +
			"\tОбработчик.Процедура = \"РегистрыНакопления.Х.Обработать\";\n" +
			"КонецПроцедуры\n",
	}
	for _, s := range seeds {
		f.Add([]byte(s))
	}

	f.Fuzz(func(t *testing.T, src []byte) {
		mod, diags := Parse(src, Options{})
		checkSpans(t, src, mod, diags, "fuzz")
	})
}
