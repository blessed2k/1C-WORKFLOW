package bsl

import "testing"

// Оба случая ниже взяты из реальной выгрузки УТ и сначала разбирались неверно
// (ADR-3, п. 4.3: 1 062 «незакрытых» метода и 1 639 ложных диагностик).
// Ожидаемое поведение выведено из того, что типовая конфигурация компилируется
// платформой: значит, и то и другое — корректный BSL.

// В типовом коде БСП поле объекта называется «Процедура»:
// Обработчик.Процедура = "…". Ключевое слово после точки — имя свойства,
// а не начало объявления метода.
func TestParseПолеСИменемПроцедураНеОбъявление(t *testing.T) {
	src := []byte("" +
		"Процедура ПриДобавленииОбработчиковОбновления(Обработчики) Экспорт\n" +
		"\tОбработчик = Обработчики.Добавить();\n" +
		"\tОбработчик.Процедура = \"РегистрыНакопления.Х.Обработать\";\n" +
		"\tОбработчик.Функция = \"Y\";\n" +
		"КонецПроцедуры\n" +
		"\n" +
		"Процедура Вторая()\n" +
		"КонецПроцедуры\n")

	mod, diags := Parse(src, Options{})
	if len(diags) != 0 {
		t.Fatalf("диагностик быть не должно: %v", codes(diags))
	}
	if len(mod.Methods) != 2 {
		t.Fatalf("методов: %d, ожидалось 2", len(mod.Methods))
	}
	if mod.Methods[0].Name != "ПриДобавленииОбработчиковОбновления" || !mod.Methods[0].Complete {
		t.Errorf("первый метод: %q Complete=%v", mod.Methods[0].Name, mod.Methods[0].Complete)
	}
	if mod.Methods[1].Name != "Вторая" {
		t.Errorf("второй метод: %q", mod.Methods[1].Name)
	}
}

// Многострочный строковый литерал: строки продолжения начинаются с '|',
// а полностью пустые строки внутри литерала платформа допускает.
func TestParseПустыеСтрокиВнутриМногострочногоЛитерала(t *testing.T) {
	src := []byte("" +
		"Функция ТекстЗапроса() Экспорт\n" +
		"\tТекстЗапроса = \"\n" +
		"\t|ВЫБРАТЬ\n" +
		"\t|\tСтроки.Период КАК Период\n" +
		"\t\n" +
		"\t\n" +
		"\t|ИЗ\n" +
		"\t|\tТаблица КАК Строки\";\n" +
		"\tВозврат ТекстЗапроса;\n" +
		"КонецФункции\n")

	mod, diags := Parse(src, Options{})
	if len(diags) != 0 {
		t.Fatalf("литерал закрыт корректно, диагностик быть не должно: %v", codes(diags))
	}
	if len(mod.Methods) != 1 || !mod.Methods[0].Complete {
		t.Fatalf("методы: %+v", mod.Methods)
	}
	// «ВЫБРАТЬ» и «ИЗ» лежат внутри строки и вызовами быть не могут.
	if len(mod.References) != 0 {
		t.Errorf("ссылок: %s, ожидалось ноль", refNames(mod))
	}
}

// Внутри многострочного литерала типовой код держит строки-комментарии «//»
// между строками продолжения: литерал при этом не обрывается.
func TestParseКомментарийВнутриМногострочногоЛитерала(t *testing.T) {
	src := []byte("" +
		"Процедура Заполнить()\n" +
		"\tЗапрос.Текст =\n" +
		"\t\"ВЫБРАТЬ РАЗЛИЧНЫЕ\n" +
		"\t|\tТаблица.Ссылка КАК Ссылка\n" +
		"\t|\n" +
		"\t// Исправить время движений документов \"\"Бронирование\"\"\n" +
		"\t|ОБЪЕДИНИТЬ ВСЕ\n" +
		"\t|ВЫБРАТЬ 1\";\n" +
		"\tВыполнить(Запрос);\n" +
		"КонецПроцедуры\n")

	mod, diags := Parse(src, Options{})
	if len(diags) != 0 {
		t.Fatalf("литерал не обрывается, диагностик быть не должно: %v", codes(diags))
	}
	if len(mod.References) != 1 || mod.Name(mod.References[0].Span) != "Выполнить" {
		t.Fatalf("ссылки: %s, ожидался единственный вызов Выполнить", refNames(mod))
	}
}
