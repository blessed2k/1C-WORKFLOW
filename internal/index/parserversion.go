// ParserVersion — версия набора фактов, которые производит пайплайн: пишется
// в source_file.parser_version при публикации и сверяется при гидратации
// корпуса (§4 спецификации прогона 3, ADR-028).
//
// Поднимать её обязан каждый, кто меняет ВЫХОД парсеров или производных
// фактов, а не только формат хранения. Цена подъёма названа прямо: одна
// полная пересборка каждого проекта после обновления сервера — гидратация
// считает файл со старой версией изменённым и перечитывает его. Цена
// НЕподъёма хуже: после перезапуска precheck честно вернёт 0, индекс объявит
// себя свежим и продолжит отдавать факты, которых новый парсер больше не
// производит, — тихая несвежесть без единого признака.
//
// 1 — исходный набор фактов.
// 2 — аннотации методов (&Вместо/&После/&Перед) в выходе parse/bsl: прогон 3,
//     перехватчики расширений.
// 3 - общий словарь видов domain.MetaKinds (C2): резолвер разрешает
//     КритерииОтбора и ХранилищаНастроек, у Sequence и ExternalDataSource
//     сменились ключи зависимостей.
// 4 - движения своего объекта через ЭтотОбъект.Движения (ThisObject.RegisterRecords)
//     в выходе parse/bsl (issue #1): register_access получает их наравне с Движения.
