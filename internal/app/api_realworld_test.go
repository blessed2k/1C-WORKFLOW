// TestRealDumpFindAPI: find_api на реальной выгрузке (написан под ut_demo, как
// и остальные real-dump тесты пакета). Ожидаемые методы выписаны руками, а не
// получены от ранжировщика: методы БСП, которые разработчик назвал бы ответом
// на запрос, и методы, названные вместе с назначением в статьях разработчиков.
// Всего 25 запросов настроечного набора (7 по БСП и 18 прикладных, из них два
// закреплены как промах) и 15 независимых.
func TestRealDumpFindAPI(t *testing.T) {
	p, _ := newRealDumpProject(t)
	svc := NewAPIService(p)
	ctx := context.Background()

	find := func(t *testing.T, query string, limit int) APISearchItem {
		t.Helper()
		t0 := time.Now()
		resp, err := svc.FindAPI(ctx, FindAPIInput{Query: query, Limit: limit})
		if err != nil {
			t.Fatalf("FindAPI(%q): %v", query, err)
		}
		item := resp.Items[0]
		t.Logf("%q: %s, bsp %d из %d, other %d из %d", query, time.Since(t0).Round(time.Millisecond),
			len(item.BSP), item.BSPMatched, len(item.Other), item.OtherMatched)
		for _, w := range resp.Warnings {
			t.Errorf("%q: предупреждение %s: %s", query, w.Code, w.Message)
		}
		return item
	}

	const top = 3
	inTop := func(items []APIMethodItem, want []string) bool {
		for i, it := range items {
			if i >= top {
				break
			}
			if slices.Contains(want, it.Call) {
				return true
			}
		}
		return false
	}

	t.Run("методы БСП в первой тройке секции bsp", func(t *testing.T) {
		for _, c := range []struct {
			query string
			want  []string
		}{
			{"значение реквизита объекта по ссылке", []string{"ОбщегоНазначения.ЗначениеРеквизитаОбъекта"}},
			{"выполнить функцию в несколько потоков в фоновых заданиях", []string{"ДлительныеОперации.ВыполнитьФункциюВНесколькоПотоков"}},
			{"разбить строку по разделителю", []string{"СтроковыеФункцииКлиентСервер.РазложитьСтрокуВМассивПодстрок"}},
			{"скачать файл из интернета", []string{"ПолучениеФайловИзИнтернета.СкачатьФайлНаСервере", "ПолучениеФайловИзИнтернета.СкачатьФайлВоВременноеХранилище"}},
			{"сумма прописью", []string{"РаботаСКурсамиВалют.СформироватьСуммуПрописью"}},
			{"проверить что ссылка существует в базе", []string{"ОбщегоНазначения.СсылкаСуществует"}},
			{"удалить недопустимые символы из имени файла", []string{"ОбщегоНазначенияКлиентСервер.ЗаменитьНедопустимыеСимволыВИмениФайла"}},
		} {
			item := find(t, c.query, 0)
			if !inTop(item.BSP, c.want) {
				t.Errorf("%q: в первой тройке bsp нет %q, есть %q", c.query, c.want, apiCalls(item.BSP))
			}
			for _, it := range item.BSP {
				if apiOverridableModule(strings.SplitN(it.Call, ".", 2)[0]) {
					t.Errorf("%q: в bsp метод переопределяемого модуля %s", c.query, it.Call)
				}
			}
		}
	})

	t.Run("прикладной метод и метод менеджера в секции other", func(t *testing.T) {
		item := find(t, "пересчитать сумму документа в валюту", 0)
		if !inTop(item.Other, []string{"РаботаСКурсамиВалютУТ.ПересчитатьСуммуДокументаВВалюту"}) {
			t.Errorf("в первой тройке other нет РаботаСКурсамиВалютУТ.ПересчитатьСуммуДокументаВВалюту, есть %q", apiCalls(item.Other))
		}
		item = find(t, "получить реквизиты для ключа цен", 0)
		if !inTop(item.Other, []string{"Справочники.ВидыНоменклатуры.ПолучитьРеквизитыДляКлючаЦен"}) {
			t.Errorf("в первой тройке other нет Справочники.ВидыНоменклатуры.ПолучитьРеквизитыДляКлючаЦен, есть %q", apiCalls(item.Other))
		}
	})

	// Прикладные методы УТ: и метод, и то, что он делает, названы в статьях
	// разработчиков (обзор функций модуля ФормированиеПечатныхФорм и обзор
	// модуля СхемыЗапросов). Формулировки запросов взяты из текста статей до
	// просмотра выдачи, наличие методов в области программного интерфейса
	// сверено по выгрузке.
	t.Run("прикладные методы из статей в первой тройке секции other", func(t *testing.T) {
		for _, c := range []struct{ query, want string }{
			{"получить данные об организации описание строкой", "ФормированиеПечатныхФорм.ОписаниеОрганизации"},
			{"адрес объекта из контактной информации на дату", "ФормированиеПечатныхФорм.ПолучитьАдресИзКонтактнойИнформации"},
			{"получить телефон из контактной информации", "ФормированиеПечатныхФорм.ПолучитьТелефонИзКонтактнойИнформации"},
			{"форматирование сумм", "ФормированиеПечатныхФорм.ФорматСумм"},
			{"сумма в рублях и копейках", "ФормированиеПечатныхФорм.СуммаРубКоп"},
			{"количество прописью", "ФормированиеПечатныхФорм.КоличествоПрописью"},
			{"вставить логотип организации в макет табличного документа", "ФормированиеПечатныхФорм.ВывестиЛоготипВТабличныйДокумент"},
			{"вывести факсимиле в табличный документ", "ФормированиеПечатныхФорм.ВывестиФаксимилеВТабличныйДокумент"},
			{"добавить поле выборки в запрос", "СхемыЗапросов.ДобавитьПолеВыборкиВЗапрос"},
			{"выборка разрешенных записей", "СхемыЗапросов.УстановитьВыборкуРазрешенныхЗаписей"},
			{"помещение запроса во временную таблицу", "СхемыЗапросов.УстановитьПомещениеВоВременнуюТаблицу"},
			{"индексировать временную таблицу по полям", "СхемыЗапросов.УстановитьИндексациюПолейЗапроса"},
			{"упорядочение по полям запроса", "СхемыЗапросов.ДобавитьПоляУпорядочиванияВЗапрос"},
			{"левое соединение в запросе", "СхемыЗапросов.ДобавитьСоединениеВЗапрос"},
			{"замена псевдонима поля в запросе", "СхемыЗапросов.ИзменитьПсевдонимПоляВыборкиВЗапросе"},
			{"удаление полей из запроса", "СхемыЗапросов.УдалитьПоляИзЗапроса"},
		} {
			item := find(t, c.query, 0)
			if !inTop(item.Other, []string{c.want}) {
				t.Errorf("%q: в первой тройке other нет %s, есть %q", c.query, c.want, apiCalls(item.Other))
			}
		}
	})

	// Два запроса из тех же статей лексический поиск не берёт: у запроса и
	// метода нет общих слов («информация об организации» против
	// СведенияОЮрФизЛице, «выборка первых» против
	// УстановитьКоличествоПолучаемыхЗаписей). Это промах, и он закреплён как
	// промах. Вторая половина закрепляет то, что обещает note инструмента: тот
	// же запрос находит метод, когда к нему дописаны слова самой конфигурации.
	t.Run("запрос без общих слов с методом: промах, с дописанными словами находит", func(t *testing.T) {
		for _, c := range []struct{ plain, added, want string }{
			{"информация об организации или контрагенте на заданный период",
				"сведения юридическом физическом лице", "ФормированиеПечатныхФорм.СведенияОЮрФизЛице"},
			{"выборка первых записей запроса",
				"количество получаемых", "СхемыЗапросов.УстановитьКоличествоПолучаемыхЗаписей"},
		} {
			if item := find(t, c.plain, 0); inTop(item.Other, []string{c.want}) {
				t.Errorf("%q: метод %s найден без дописанных слов: оговорка в docs/tools-index.md устарела, запрос переносится в таблицу выше", c.plain, c.want)
			}
			augmented := c.plain + " " + c.added
			if item := find(t, augmented, 0); !inTop(item.Other, []string{c.want}) {
				t.Errorf("%q: в первой тройке other нет %s, есть %q", augmented, c.want, apiCalls(item.Other))
			}
		}
	})

	// Независимый набор: методы ОбщегоНазначения и то, что они делают, названы
	// в третьей статье («Базовые вещи БСП»), формулировки взяты из её текста.
	// Правила ранжирования на этих запросах НЕ настраивались. С поиском по
	// полному комментарию в первой тройке 10 из 15 (по одной первой строке
	// было 9, у самого первого правила 6). Порог закрепляет достигнутое;
	// запрос, начавший находиться, порог только поднимает. Оценку качества
	// даёт не этот набор, а эталон evals/findapi (docs/find-api-eval.md).
	t.Run("независимый набор запросов по БСП", func(t *testing.T) {
		const wantInTop = 10
		hits := 0
		for _, c := range []struct{ query, want string }{
			{"получить выбранные реквизиты по ссылке", "ОбщегоНазначения.ЗначенияРеквизитовОбъекта"},
			{"реквизиты по массиву ссылок", "ОбщегоНазначения.ЗначенияРеквизитовОбъектов"},
			{"массив непроведенных документов", "ОбщегоНазначения.ПроверитьПроведенностьДокументов"},
			{"провести документы и вернуть описание ошибок", "ОбщегоНазначения.ПровестиДокументы"},
			{"проверка есть ли ссылки на объект", "ОбщегоНазначения.ЕстьСсылкиНаОбъект"},
			{"где используется объект таблица значений", "ОбщегоНазначения.МестаИспользования"},
			{"информация о подсистемах и библиотеках включенных в конфигурацию", "ОбщегоНазначения.ОписанияПодсистем"},
			{"настройки базовой функциональности конфигурации", "ОбщегоНазначения.ОбщиеПараметрыБазовойФункциональности"},
			{"является ли информационная база файловой", "ОбщегоНазначения.ИнформационнаяБазаФайловая"},
			{"объем оперативной памяти доступной приложению", "ОбщегоНазначения.ОперативнаяПамятьДоступнаяКлиентскомуПриложению"},
			{"номер редакции конфигурации", "ОбщегоНазначения.РедакцияКонфигурации"},
			{"пользователь работает под windows на клиенте", "ОбщегоНазначения.ЭтоWindowsКлиент"},
			{"дата со смещением по часовому поясу", "ОбщегоНазначения.ПредставлениеЛокальнойДатыСоСмещением"},
			{"интервал времени строкой", "ОбщегоНазначения.ИнтервалВремениСтрокой"},
			{"текущая дата пользователя", "ОбщегоНазначения.ТекущаяДатаПользователя"},
		} {
			item := find(t, c.query, 0)
			if inTop(item.BSP, []string{c.want}) {
				hits++
			} else {
				t.Logf("%q: в первой тройке bsp нет %s, есть %q", c.query, c.want, apiCalls(item.BSP)[:min(3, len(item.BSP))])
			}
		}
		t.Logf("независимый набор: в первой тройке %d из 15", hits)
		if hits < wantInTop {
			t.Errorf("независимый набор: в первой тройке %d из 15, было %d", hits, wantInTop)
		}
	})

	t.Run("устаревший метод помечен и называет замену", func(t *testing.T) {
		item := find(t, "идентификатор рабочего стола", maxAPILimit)
		i := slices.IndexFunc(item.BSP, func(it APIMethodItem) bool {
			return it.Call == "ДополнительныеОтчетыИОбработкиКлиентСервер.ИдентификаторРабочегоСтола"
		})
		if i < 0 {
			t.Fatalf("устаревший метод не найден в bsp: %q", apiCalls(item.BSP))
		}
		if got := item.BSP[i]; !got.Deprecated || !strings.Contains(got.Summary, "Следует использовать") {
			t.Errorf("устаревший метод: deprecated = %v, summary = %q", got.Deprecated, got.Summary)
		}
	})

	t.Run("замер частей вызова", func(t *testing.T) {
		op, err := p.Active(ctx)
		if err != nil {
			t.Fatalf("Active: %v", err)
		}
		type parts struct {
			rows, objects    int
			methods, library time.Duration
		}
		got, err := readTx(ctx, op.Store, func(tx *store.ReadTx) (parts, error) {
			var out parts
			t0 := time.Now()
			rows, err := tx.ExportedMethodsInRegions(apiModuleKinds, apiTopRegions)
			if err != nil {
				return out, err
			}
			out.rows, out.methods = len(rows), time.Since(t0)
			t0 = time.Now()
			lib, err := readAPILibrary(tx)
			if err != nil {
				return out, err
			}
			out.objects, out.library = len(lib.objects), time.Since(t0)
			return out, nil
		})
		if err != nil {
			t.Fatalf("readTx: %v", err)
		}
		t.Logf("методов программного интерфейса %d за %s; состав библиотеки %d объектов за %s",
			got.rows, got.methods.Round(time.Millisecond), got.objects, got.library.Round(time.Millisecond))
		if got.rows == 0 || got.objects == 0 {
			t.Errorf("пустой замер: методов %d, объектов библиотеки %d", got.rows, got.objects)
		}
	})

	t.Run("версия библиотеки прочитана из выгрузки", func(t *testing.T) {
		item := find(t, "значение реквизита объекта", 0)
		if !regexp.MustCompile(`^\d+\.\d+\.\d+\.\d+$`).MatchString(item.BSPVersion) {
			t.Errorf("BSPVersion = %q, want вида 3.1.11.366", item.BSPVersion)
		}
		t.Logf("версия БСП: %s", item.BSPVersion)
	})
}
