func TestAPIDocTypes(t *testing.T) {
	for _, tc := range []struct {
		name    string
		doc     string
		returns []string
		params  []string
	}{
		{name: "тип и описание", doc: "Возвращает остатки.\n\nПараметры:\nСклад - СправочникСсылка.Склады - склад.\nДата - Дата, Неопределено - на дату.\n\nВозвращаемое значение:\nТаблицаЗначений - остатки по складу.",
			returns: []string{"ТаблицаЗначений"}, params: []string{"СправочникСсылка.Склады", "Дата, Неопределено"}},
		{name: "структура с полями", doc: "Возвращаемое значение:\nСтруктура:\n* Группа - ГруппаФормы - место.\n* Имя - Строка - имя.",
			returns: []string{"Структура"}},
		{name: "варианты результата", doc: "Возвращаемое значение:\nСтруктура:\n* Соединение - COMОбъект\n- Неопределено - в случае ошибки;",
			returns: []string{"Структура", "Неопределено"}},
		{name: "коллекция", doc: "Возвращаемое значение:\nМассив из ПеречислениеСсылка.Статусы - статусы",
			returns: []string{"Массив из ПеречислениеСсылка.Статусы"}},
		{name: "тип на строке заголовка", doc: "Возвращаемое значение: Строка - имя.", returns: []string{"Строка"}},
		{name: "ссылка на другой метод", doc: "Возвращаемое значение:\nсм. СвойстваСертификата"},
		{name: "коллекция со ссылкой", doc: "Возвращаемое значение:\nМассив из см. НовоеОписаниеСтроки", returns: []string{"Массив"}},
		{name: "тип и ссылка", doc: "Возвращаемое значение:\nСтруктура, см. НовыеПараметры - параметры.", returns: []string{"Структура"}},
		{name: "описание словами", doc: "Возвращаемое значение:\nИстина, если запись прошла успешно."},
		{name: "значение вместо типа", doc: "Возвращаемое значение:\nИстина - если запись прошла успешно."},
		{name: "поля структуры без звёздочки не типы", doc: "Возвращаемое значение:\nСтруктура - описание:\nКлюч - Строка - ключ.\nЗначение - Число - значение.\nВажно:\nРезультат кэшируется.",
			returns: []string{"Структура"}},
		{name: "лишние пробелы и хвост", doc: "Возвращаемое значение:\nБулево   - Истина, если успешно.\n- Строка  -", returns: []string{"Булево", "Строка"}},
		{name: "повтор типа", doc: "Возвращаемое значение:\nСтрока - имя.\n- Строка - представление.", returns: []string{"Строка"}},
		{name: "поля параметра не параметры", doc: "Параметры:\nНастройки - Структура:\n* Имя - Строка - имя.\nОтказ - Булево - признак.\n- Неопределено - отказа нет.\nПример:\nА - Число - это уже пример.",
			params: []string{"Структура", "Булево", "Неопределено"}},
		{name: "длинная структура не съедает параметры", doc: "Параметры:\nНастройки - Структура:\n" + repeatLine("* Поле - Строка - поле.\n", 250) + "Отказ - Булево - признак.",
			params: []string{"Структура", "Булево"}},
		{name: "без разделов", doc: "Просто делает дело."},
	} {
		t.Run(tc.name, func(t *testing.T) {
			returns, params := apiDocTypes(tc.doc)
			if !reflect.DeepEqual(returns, tc.returns) || !reflect.DeepEqual(params, tc.params) {
				t.Errorf("типы = %q и %q, want %q и %q", returns, params, tc.returns, tc.params)
			}
		})
	}
}

func repeatLine(line string, n int) string {
	out := ""
	for i := 0; i < n; i++ {
		out += line
	}
	return out
}

// TestAPITypesMatch: имя типа сравнивается целиком или до точки, а не
// подстрокой: «Строка» не находит СтрокаТаблицыЗначений, «Запрос» не находит
// РезультатЗапроса.
func TestAPITypesMatch(t *testing.T) {
	types := []string{"Массив из ТаблицаЗначений", "ДокументСсылка.ЗаказКлиента, Неопределено", "СтрокаТаблицыЗначений", "РезультатЗапроса"}
	for want, ok := range map[string]bool{
		"ТаблицаЗначений": true, "таблица значений": true, "ДокументСсылка": true, "ДокументСсылка.ЗаказКлиента": true,
		"Неопределено": true, "Массив": true, "Структура": false, "Строка": false, "Запрос": false, "Ссылка": false, "из": false, "": true,
	} {
		if got := apiTypesMatch(types, want); got != ok {
			t.Errorf("apiTypesMatch(%q) = %v, want %v", want, got, ok)
		}
	}
	if apiTypesMatch(nil, "Строка") {
		t.Errorf("метод без типов в комментарии подошёл под отбор по типу")
	}
}
