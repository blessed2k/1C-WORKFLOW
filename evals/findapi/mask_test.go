// TestMaskHidesMethodName: во фрагменте не остаётся имени метода ни в вызове
// через модуль, ни в другом регистре, ни в комментарии, ни в строке; имя
// модуля, через который метод позван, скрыто вместе с ним.
func TestMaskHidesMethodName(t *testing.T) {
	const method = "ЗначениеРеквизитаОбъекта"
	snippet, ok := buildSnippet(maskFixture, 9, method)
	if !ok {
		t.Fatalf("buildSnippet: фрагмент отвергнут")
	}
	if mentions(snippet, method) {
		t.Errorf("во фрагменте осталось имя метода:\n%s", snippet)
	}
	for _, want := range []string{
		"// Заполняет наименование контрагента в шапке документа.",
		"// См. " + maskedName + ".",
		"&НаСервере",
		"Процедура ЗаполнитьНаименованиеКонтрагента(Документ)",
		"Наименование = " + maskedName + `(Документ.Контрагент, "Наименование");`,
		"Код = " + maskedName + `(Документ.Контрагент, "Код").Значение;`,
		`Имя = "` + maskedName + `";`,
		// Другой метод с похожим именем остаётся как есть.
		"ОбщегоНазначения.ЗначенияРеквизитовОбъекта(Документ.Контрагент",
		// Имя-надстройка над именем метода скрыто в своей части.
		"Кэш = " + maskedName + "ИзКэша(Документ);",
		"КонецПроцедуры",
	} {
		if !strings.Contains(snippet, want) {
			t.Errorf("во фрагменте нет %q:\n%s", want, snippet)
		}
	}
	if strings.Contains(snippet, "Функция") {
		t.Errorf("фрагмент вышел за границы вызывающей процедуры:\n%s", snippet)
	}
}

// TestBuildSnippetRejects: фрагмент, по которому о методе ничего не узнать,
// отвергается.
func TestBuildSnippetRejects(t *testing.T) {
	const method = "ЗначениеРеквизитаОбъекта"
	for name, line := range map[string]int{
		"обёртка с тем же именем":   19,
		"вызов в теле модуля":       22,
		"на строке нет метода":      10,
		"строка за пределами файла": 500,
		"строка заголовка":          7,
	} {
		if snippet, ok := buildSnippet(maskFixture, line, method); ok {
			t.Errorf("%s (строка %d): фрагмент принят:\n%s", name, line, snippet)
		}
	}
}

// TestCallerNamesMethod: фрагмент отвергается, когда имя вызывающей процедуры
// выдаёт имя метода: то же имя, имя-надстройка или две трети тех же слов.
func TestCallerNamesMethod(t *testing.T) {
	for _, c := range []struct {
		caller, method string
		want           bool
	}{
		{"ЗначениеРеквизитаОбъекта", "ЗначениеРеквизитаОбъекта", true},
		{"значениереквизитаобъекта", "ЗначениеРеквизитаОбъекта", true},
		{"ЗначениеРеквизитаОбъектаНаСервере", "ЗначениеРеквизитаОбъекта", true},
		{"ВерсииИнтерфейсаЧерезВнешнееСоединение", "ПолучитьВерсииИнтерфейсаЧерезВнешнееСоединение", true},
		{"ОбработкаПроверкиЗаполненияНаСервере", "ОбработкаПроверкиЗаполнения", true},
		{"ЗаполнитьНаименованиеКонтрагента", "ЗначениеРеквизитаОбъекта", false},
		{"ПрочитатьРеквизитОбъекта", "ЗначениеРеквизитаОбъекта", false},
		// Имя из одного слова это обычное слово: совпадение части не выдаёт метод.
		{"ЗаполнитьТовары", "Заполнить", false},
		{"Заполнить", "Заполнить", true},
	} {
		if got := callerNamesMethod(c.caller, c.method); got != c.want {
			t.Errorf("callerNamesMethod(%q, %q) = %v, want %v", c.caller, c.method, got, c.want)
		}
	}
	src := "Процедура ОбработкаПроверкиЗаполненияНаСервере(Отказ)\n\tМодуль.ОбработкаПроверкиЗаполнения(Отказ);\nКонецПроцедуры\n"
	if snippet, ok := buildSnippet(src, 2, "ОбработкаПроверкиЗаполнения"); ok {
		t.Errorf("фрагмент с именем-надстройкой в заголовке принят:\n%s", snippet)
	}
}

