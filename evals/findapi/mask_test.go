// TestMethodDoc: полный комментарий метода читается вместе с параметрами,
// директива компиляции между комментарием и объявлением не мешает.
func TestMethodDoc(t *testing.T) {
	src := `Перем А;

// Возвращает значение реквизита.
//
// Параметры:
//  Ссылка - ЛюбаяСсылка - объект.
//
&НаСервере
Функция Значение(Ссылка) Экспорт
КонецФункции

Функция БезОписания() Экспорт
КонецФункции
`
	want := "Возвращает значение реквизита.\n\nПараметры:\n Ссылка - ЛюбаяСсылка - объект."
	if got := methodDoc(src, 9); got != want {
		t.Errorf("methodDoc = %q, want %q", got, want)
	}
	if got := methodDoc(src, 12); got != "" {
		t.Errorf("methodDoc метода без описания = %q, want пусто", got)
	}
	if got := methodDoc(src, 500); got != "" {
		t.Errorf("methodDoc строки за пределами файла = %q, want пусто", got)
	}
}
